// Builds the authoritative room logic: maps.js + sim.js + server/glue.js -> dist/dread_logic.js (one script, no imports).
// Usage: node tools/build-logic.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const strip = src => src
  .replace(/^import .*$/gm, '')
  .replace(/^export \{[^}]*\};?$/gm, '')
  .replace(/^export (const|let|function|class) /gm, '$1 ');
const parts = ['src/maps.js', 'src/sim.js', 'server/glue.js'].map(f => `// ===== ${f} =====\n` + strip(readFileSync(join(root, f), 'utf8')));
const out = '// DREAD room logic (generated by tools/build-logic.mjs, do not edit)\n' + parts.join('\n');
mkdirSync(join(root, 'dist'), { recursive: true });
writeFileSync(join(root, 'dist/dread_logic.js'), out);
console.log(`dist/dread_logic.js ${out.length} bytes`);
if (out.length > 256 * 1024) { console.error('too big for deploy_room_logic (256 KB)'); process.exit(1); }
